UPDATE dbo.PATIENTS_Patient
SET DHCS_LAST_NAME = NULL
WHERE ACTIVE != 'n' AND DHCS_LAST_NAME = ''

UPDATE dbo.PATIENTS_Patient
SET DHCS_FIRST_NAME = NULL
WHERE ACTIVE != 'n' AND DHCS_FIRST_NAME = ''

UPDATE dbo.PATIENTS_Patient
SET BIC = NULL
WHERE BIC = ''

UPDATE dbo.PATIENTS_Patient
SET DHCS_FIRST_NAME = NULL,
    DHCS_LAST_NAME = NULL
WHERE BIC IS NULL

GO

IF NOT EXISTS(SELECT * FROM sys.columns WHERE Name = 'DHCS_DOB' AND Object_ID = Object_ID('dbo.PATIENTS_Patient'))
  ALTER TABLE PATIENTS_Patient add DHCS_DOB date

IF NOT EXISTS(SELECT * FROM sys.columns WHERE Name = 'DHCS_SEX' AND Object_ID = Object_ID('dbo.PATIENTS_Patient'))
  ALTER TABLE PATIENTS_Patient add DHCS_SEX char(1)

GO

UPDATE dbo.PATIENTS_Patient
SET DHCS_FIRST_NAME  = COALESCE(DHCS_FIRST_NAME,FIRST_NAME),
    DHCS_LAST_NAME   = COALESCE(DHCS_LAST_NAME,LAST_NAME),
    DHCS_MIDDLE_NAME = COALESCE(DHCS_MIDDLE_NAME,MIDDLE_NAME),
    DHCS_SEX = COALESCE(DHCS_SEX,SEX),
    DHCS_DOB = COALESCE(DHCS_DOB,DATE_OF_BIRTH)
WHERE Active != 'n' AND BIC IS NOT NULL

GO